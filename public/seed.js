const CHO = ['ㄱ','ㄲ','ㄴ','ㄷ','ㄸ','ㄹ','ㅁ','ㅂ','ㅃ','ㅅ','ㅆ','ㅇ','ㅈ','ㅉ','ㅊ','ㅋ','ㅌ','ㅍ','ㅎ'];

// 단어의 첫 글자 초성을 돌려줍니다. 한글이 아니면 null.
export function initialOf(word) {
  if (!word) return null;
  const code = word.normalize('NFC').charCodeAt(0) - 0xac00;
  if (code < 0 || code > 11171) return null;
  return CHO[Math.floor(code / 588)];
}

// 저장 이미지 파일명 (한글 파일명 문제를 피하려고 코드값으로 변환)
export function imgKey(word) {
  return [...word.normalize('NFC')].map((ch) => ch.charCodeAt(0).toString(16)).join('-');
}

// 'ㄱ으로', 'ㄹ로' 처럼 조사를 붙입니다.
export function withRo(c) {
  return c === 'ㄹ' ? `${c}로` : `${c}으로`;
}

